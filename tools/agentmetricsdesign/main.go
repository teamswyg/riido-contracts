package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"
)

const (
	manifestPath = "docs/20-domain/agent-response-metrics.riido.json"
	docPath      = "docs/20-domain/agent-response-metrics.md"
)

type (
	metric struct{ Name, Meaning string }
	sample struct {
		Version    string
		DaemonMS   int64 `json:"daemon_ms"`
		ProviderMS int64 `json:"provider_ms"`
		PostMS     int64 `json:"post_provider_ms"`
		FirstMS    int64 `json:"first_nonblank_ms"`
		Characters int   `json:"text_characters"`
		Events     int   `json:"text_delta_events"`
	}
)

type contract struct {
	Schema               string `json:"schema_version"`
	Title                string
	Target               int    `json:"target_ms"`
	Minimum              int    `json:"minimum_percentile_samples"`
	Unknown              int    `json:"unknown_duration"`
	Provenance           string `json:"baseline_provenance"`
	Baseline             []sample
	Metrics              []metric
	Acceptance, Evidence []string
}

func validate(d contract) error {
	if d.Schema != "riido-agent-response-metrics.v1" || d.Target != 10000 || d.Minimum < 20 || d.Unknown != -1 || len(d.Baseline) != 2 {
		return errors.New("invalid metric identity, target, or sampling boundary")
	}
	seen := map[string]bool{}
	for _, m := range d.Metrics {
		if m.Name == "" || m.Meaning == "" || seen[m.Name] {
			return errors.New("missing or duplicate metric")
		}
		seen[m.Name] = true
	}
	for _, required := range []string{"claim_to_terminal_ms", "claim_to_first_text_ms", "provider_elapsed_ms", "post_provider_ms", "mailbox_wait_max_ms", "event_processing_ms", "text_delta_events", "text_characters"} {
		if !seen[required] {
			return errors.New("missing pipeline metric")
		}
	}
	if d.Provenance == "" || len(d.Acceptance) < 5 || len(d.Evidence) < 6 {
		return errors.New("missing verification or privacy boundary")
	}
	return nil
}

func render(d contract) string {
	var out strings.Builder
	fmt.Fprintf(&out, "# %s\n\n<!-- Generated by go run ./tools/agentmetricsdesign -write-doc. Do not edit by hand. -->\n\nSSOT: [agent-response-metrics.riido.json](agent-response-metrics.riido.json).\n\n전체 목표: **%dms 미만**. 누락 시간: **%d**. p95 최소 표본: **%d**.\n\n## 사용자 기준 표본\n\n%s\n\n| 버전 | daemon 완료 ms | adapter/모델 관측 ms | 완료 후 전달 ms | 첫 비공백 ms | 문자 | 원본 TextDelta |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n", d.Title, d.Target, d.Unknown, d.Minimum, d.Provenance)
	for _, s := range d.Baseline {
		fmt.Fprintf(&out, "| %s | %d | %d | %d | %d | %d | %d |\n", s.Version, s.DaemonMS, s.ProviderMS, s.PostMS, s.FirstMS, s.Characters, s.Events)
	}
	out.WriteString("\n## 단계별 지표\n\n| 지표 | 의미 |\n| --- | --- |\n")
	for _, m := range d.Metrics {
		fmt.Fprintf(&out, "| `%s` | %s |\n", m.Name, m.Meaning)
	}
	for _, section := range []struct {
		title string
		rows  []string
	}{{"판정과 개선", d.Acceptance}, {"수집·분석·예약·배포", d.Evidence}} {
		fmt.Fprintf(&out, "\n## %s\n\n", section.title)
		for _, row := range section.rows {
			fmt.Fprintf(&out, "- %s\n", row)
		}
	}
	return out.String()
}

func main() {
	write := flag.Bool("write-doc", false, "regenerate reader document")
	flag.Parse()
	body, err := os.ReadFile(manifestPath)
	var d contract
	if err == nil {
		err = json.Unmarshal(body, &d)
	}
	if err == nil {
		err = validate(d)
	}
	if err == nil {
		want := render(d)
		if *write {
			err = os.WriteFile(docPath, []byte(want), 0o644)
		} else {
			var got []byte
			got, err = os.ReadFile(docPath)
			if err == nil && string(got) != want {
				err = errors.New("agent metric document drift")
			}
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
