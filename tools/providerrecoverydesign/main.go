package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"
)

type transition struct {
	Source               string `json:"source"`
	Target               string `json:"target"`
	Event                string `json:"event"`
	BudgetRequired       bool   `json:"budget_required"`
	VerificationRequired bool   `json:"verification_required"`
}

type section struct {
	Title string `json:"title"`
	Body  string `json:"body"`
}

type design struct {
	SchemaVersion      string       `json:"schema_version"`
	Title              string       `json:"title"`
	Status             string       `json:"status"`
	GeneratedDoc       string       `json:"generated_doc"`
	States             []string     `json:"states"`
	Start              string       `json:"start"`
	Terminals          []string     `json:"terminals"`
	UnknownEventTarget string       `json:"unknown_event_target"`
	Transitions        []transition `json:"transitions"`
	Sections           []section    `json:"sections"`
}

func validate(d design) error {
	if d.SchemaVersion != "riido-provider-recovery-design.v1" || d.GeneratedDoc != "docs/20-domain/provider-recovery.md" {
		return errors.New("invalid recovery design identity")
	}
	states, ends := map[string]bool{}, map[string]bool{}
	for _, state := range d.States {
		if state == "" || states[state] || strings.ContainsAny(state, " \n\r[]:") {
			return errors.New("invalid or duplicate recovery state")
		}
		states[state] = true
	}
	for _, end := range d.Terminals {
		if !states[end] {
			return errors.New("unknown terminal")
		}
		ends[end] = true
	}
	if !states[d.Start] || !ends["RECOVERED"] || !ends["TERMINAL"] || d.UnknownEventTarget != "TERMINAL" {
		return errors.New("missing start, success, or safe unknown exit")
	}
	paths := map[string][]string{}
	seen := map[string]bool{}
	for _, t := range d.Transitions {
		key := t.Source + "\x00" + t.Event
		if !states[t.Source] || !states[t.Target] || ends[t.Source] || t.Event == "" || seen[key] {
			return errors.New("invalid or conflicting recovery transition")
		}
		seen[key] = true
		if (t.Target == "REPAIRING" || t.Target == "SWITCHING" || t.Source == "REPAIRING" || t.Source == "SWITCHING" || t.Source == "WAITING_USER" && t.Target == "VERIFYING") && !t.BudgetRequired {
			return errors.New("recovery action/retry requires a finite budget")
		}
		if t.Target == "RECOVERED" && (!t.VerificationRequired || t.Source != "VERIFYING" && t.Source != "VERIFYING_SWITCH") {
			return errors.New("recovered requires explicit functional verification")
		}
		paths[t.Source] = append(paths[t.Source], t.Target)
	}
	for state := range states {
		visited := map[string]bool{}
		var reachesEnd func(string) bool
		reachesEnd = func(current string) bool {
			if ends[current] {
				return true
			}
			if visited[current] {
				return false
			}
			visited[current] = true
			for _, next := range paths[current] {
				if reachesEnd(next) {
					return true
				}
			}
			return false
		}
		if !reachesEnd(state) {
			return fmt.Errorf("recovery state %s has no terminal path", state)
		}
	}
	return nil
}

func render(d design) string {
	var out strings.Builder
	fmt.Fprintf(&out, "# %s\n\n<!-- Generated by go run ./tools/providerrecoverydesign -write-doc. Do not edit by hand. -->\n\nSSOT: [provider-recovery.riido.json](provider-recovery.riido.json).\n\n**상태:** %s\n\n", d.Title, d.Status)
	for _, s := range d.Sections {
		fmt.Fprintf(&out, "## %s\n\n%s\n\n", s.Title, s.Body)
	}
	out.WriteString("## 전체 책임 구조\n\n```mermaid\nflowchart TD\n")
	for _, edge := range [][2]string{{"Supervisor", "Discovery"}, {"Supervisor", "Installation"}, {"Supervisor", "Authentication"}, {"Supervisor", "Authorization"}, {"Supervisor", "Capability"}, {"Supervisor", "Execution"}, {"Execution", "Detection"}, {"Detection", "Diagnosis"}, {"Diagnosis", "Recovery"}, {"Recovery", "Performance"}, {"Recovery", "Failover"}, {"Recovery", "Notification"}, {"Failover", "Notification"}} {
		fmt.Fprintf(&out, "  %s --> %s\n", edge[0], edge[1])
	}
	out.WriteString("```\n\n## 공통 장애 복구 FSM · 설계\n\n```mermaid\nstateDiagram-v2\n")
	fmt.Fprintf(&out, "  [*] --> %s\n", d.Start)
	for _, t := range d.Transitions {
		fmt.Fprintf(&out, "  %s --> %s: %s\n", t.Source, t.Target, t.Event)
	}
	for _, end := range d.Terminals {
		fmt.Fprintf(&out, "  %s --> [*]\n", end)
	}
	out.WriteString("```\n\n알 수 없는 event는 `TERMINAL`로 안전하게 종결한다. 그래프의 종결 경로는 구조 검증이며 runtime의 시간·횟수 상한은 adapter 실행 구현에서 별도 증명해야 한다.\n")
	return out.String()
}

func run() error {
	write := flag.Bool("write-doc", false, "regenerate reader document")
	flag.Bool("check-doc", false, "verify reader document")
	flag.Parse()
	body, err := os.ReadFile("docs/20-domain/provider-recovery.riido.json")
	if err != nil {
		return err
	}
	var d design
	if err := json.Unmarshal(body, &d); err != nil {
		return err
	}
	if err := validate(d); err != nil {
		return err
	}
	want := render(d)
	if *write {
		return os.WriteFile(d.GeneratedDoc, []byte(want), 0o644)
	}
	got, err := os.ReadFile(d.GeneratedDoc)
	if err != nil {
		return err
	}
	if string(got) != want {
		return errors.New("provider recovery design document drift")
	}
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
